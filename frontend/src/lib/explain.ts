/** The page key for a portal address: "/" is the Overview, "/vault" the Evidence Vault. */
export function pageOf(pathname: string): string {
  return pathname.split('/').filter(Boolean)[0] ?? 'overview';
}

/** A key written as /pattern/ matches titles that change with the data, e.g. "Untraced in October 2026 · 2". */
function lookup(table: Record<string, string> | undefined, key: string): string | undefined {
  if (!table) return undefined;
  if (table[key]) return table[key];
  for (const [k, text] of Object.entries(table)) {
    if (k.length > 2 && k.startsWith('/') && k.endsWith('/') && new RegExp(k.slice(1, -1)).test(key)) return text;
  }
  return undefined;
}

export function explanationFor(pathname: string, title: string): string | undefined {
  const key = title.replace(/\s+/g, ' ').trim();
  return lookup(EXPLAIN[pageOf(pathname)], key) ?? lookup(EXPLAIN['*'], key);
}
